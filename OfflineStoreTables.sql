CREATE TABLE IF NOT EXISTS Customer (
	CustomerId INTEGER PRIMARY KEY AUTOINCREMENT,
	Name NVARCHAR(50) NOT NULL,
  	Surname NVARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS Category (
	CategoryId INTEGER PRIMARY KEY AUTOINCREMENT,
	Name NVARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS Product (
	ProductId INTEGER PRIMARY KEY AUTOINCREMENT,
	CategoryId INTEGER NOT NULL,
	Name NVARCHAR(50) NOT NULL,
	Price INTEGER NOT NULL,
	Stock INTEGER NOT NULL,
	
	CONSTRAINT FK_Product_Category FOREIGN KEY (CategoryId) REFERENCES Category (CategoryId)
);

CREATE TABLE IF NOT EXISTS OrderItem (
	OrderItemId INTEGER PRIMARY KEY AUTOINCREMENT,
	ProductId INTEGER NOT NULL,
	OrderId INTEGER NOT NULL,
	PricePaid INTEGER NOT NULL,
	Quantity INTEGER NOT NULL,
	
	CONSTRAINT FK_OrderItem_Product FOREIGN KEY (ProductId) REFERENCES Product (ProductId),
	CONSTRAINT FK_OrderItem_Orders FOREIGN KEY (OrderId) REFERENCES Orders (OrderId)
);

CREATE TABLE IF NOT EXISTS CartItem (
	CartItemId INTEGER PRIMARY KEY AUTOINCREMENT,
	ProductId INTEGER NOT NULL,
	CustomerId INTEGER NOT NULL,
	Quantity INTEGER NOT NULL,
	LineTotal INTEGER NOT NULL ,
	
	CONSTRAINT FK_CartItem_Product FOREIGN KEY (ProductId) REFERENCES Product (ProductId),
	CONSTRAINT FK_CartItem_Customer FOREIGN KEY (CustomerId) REFERENCES Customer (CustomerId)
);

CREATE TABLE IF NOT EXISTS Orders (
	OrdersId INTEGER PRIMARY KEY AUTOINCREMENT,
	CustomerId INTEGER NOT NULL,
	OrdersDate DATETIME NOT NULL,
	OrdersTotal INTEGER NOT NULL,
	
	CONSTRAINT FK_Orders_Customer FOREIGN KEY (CustomerId) REFERENCES Customer (CustomerId)
);